// Package mixed 實作日文與英文混打的共用規則。
//
// 這一層不改變注音中英混打，也不改日文かな漢字変換本身。它提供四件事：
//
//   - Composer：包住 core/ja/input 的組字器，讓 ASCII 英數、網址、email 與
//     識別字照字面留在讀音序列裡，其餘羅馬字仍走原本的かな組字。英文字可以
//     用 core/english 的詞典自動補完。
//   - Converter：包住日文 converter，把讀音序列切成日文段與照字面段，只把
//     日文段交給底層変換。因此英文、網址與 email 不會被當成かな変換，文節
//     也只由日文段決定。
//   - Token / Classify：辨認網址、email、識別字、全角英數與英文詞的邊界。
//   - SpaceText：日文與英文之間是否補空白的規則。日文慣例是不補，預設值
//     與注音的「中英之間自動加空格」不同，必須由呼叫端明確打開。
//
// 辨識英文字與羅馬字的優先順序：
//
//  1. 大寫、全角、數字、網址、email、識別字與使用者學過的詞一律照字面。
//  2. 小寫且是 core/english 詞典裡的完整單字，照字面（長度由 Config 控制）。
//  3. 其餘依原本的羅馬字表組かな。打不成合法羅馬字（例如 kubectl、github）
//     時也照字面，避免整串變成かな。
//
// 因此「code」「sake」這種同時是英文與羅馬字的短字仍有歧義：前者在預設詞典
// 裡，會照英文；後者不在詞典裡，照かな。使用者可以用 AcceptEnglish 明確鎖定
// 英文，或把它學進 English 詞彙。
//
// SpaceText 預設 SpacingNone。要補空白時由呼叫端設定 SpacingAlways；轉換器
// 會在相鄰文節之間套用同一規則，送出前也可以再對整段文字呼叫一次。沒有經過
// 変換就直接送出的かな（例如只按 Enter）不會自動加空白，宿主可對送出文字呼叫
// SpaceText，或先經過一次変換。
